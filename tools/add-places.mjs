// ---------------------------------------------------------------- Kategorien
const CAT_CAFE = {
  id: "cafe",
  label: "Kaffee & Bäckerei",
  short: "Kaffee & Bäckerei",
  color: "#9a5b21",
  icon: "☕",
};
const CAT_SERVICES = {
  id: "services",
  label: "Praktisches",
  short: "Praktisches",
  color: "#64748b",
  icon: "ℹ️",
};

const hasCat = (id) => data.categories.some((c) => c.id === id);
if (!hasCat("cafe")) {
  const i = data.categories.findIndex((c) => c.id === "restaurant");
  data.categories.splice(i < 0 ? data.categories.length : i, 0, CAT_CAFE);
}
if (!hasCat("services")) data.categories.push(CAT_SERVICES);

// ------------------------------------------------- Bäckereien verschieben
